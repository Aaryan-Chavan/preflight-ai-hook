import os
import stat
import subprocess
from pathlib import Path
from rich.console import Console

console = Console()

def get_git_root() -> Path:
    """Finds the root of the current Git repository."""
    try:
        git_root = subprocess.check_output(
            ["git", "rev-parse", "--show-toplevel"], 
            stderr=subprocess.DEVNULL
        ).decode().strip()
        return Path(git_root)
    except Exception:
        return None

def install_git_hook():
    """Installs the pre-push bash script into the user's local .git/hooks directory."""
    git_root = get_git_root()
    
    if not git_root:
        console.print("[red]Error: Not inside a Git repository. Please navigate to a project folder and try again.[/red]")
        return
        
    hooks_dir = git_root / ".git" / "hooks"
    pre_push_path = hooks_dir / "pre-push"
    
    # The bash script that Git will execute during a push
    hook_script = """#!/bin/bash
# Preflight AI - Autonomous Quality Gate
# Automatically generated by `preflight init`

echo "🚀 [Preflight AI] Analyzing commit telemetry..."

# Route execution to our installed Python package
preflight run-hook

# Capture the exit code of our Python script
EXIT_CODE=$?

if [ $EXIT_CODE -ne 0 ]; then
  echo "❌ [Preflight AI] Push blocked due to critical security violations."
  exit 1
fi

echo "✅ [Preflight AI] Gates passed. Proceeding with push."
exit 0
"""
    
    try:
        # Create the hook file
        with open(pre_push_path, "w") as f:
            f.write(hook_script)
            
        # Make the bash script executable (chmod +x)
        st = os.stat(pre_push_path)
        os.chmod(pre_push_path, st.st_mode | stat.S_IEXEC)
        
    except Exception as e:
        console.print(f"[red]Failed to install hook: {e}[/red]")
        raise